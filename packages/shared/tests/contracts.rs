//! Milestone 1 acceptance: the contracts compile on both sides and agree on the wire.
//!
//! 1. Exports TypeScript bindings for every contract to `ts/generated/`.
//! 2. Parses every fixture in `fixtures/` into its Rust type and checks it
//!    serialises back to exactly the same JSON (no dropped, renamed or extra fields).
//! 3. Writes the same fixtures to `ts/generated/fixtures.ts` as typed constants,
//!    so `tsc` checks them against the generated types.

use std::fs;
use std::path::PathBuf;

use nudgy_shared::*;
use serde::Serialize;
use serde::de::DeserializeOwned;
use serde_json::Value;
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by `cargo test -p nudgy-shared`. Do not edit.\n\n";

fn package_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn config() -> Config {
    Config::new()
        .with_out_dir(package_dir().join("ts").join("generated"))
        // Timestamps are i64 milliseconds; a JS number holds them exactly.
        .with_large_int("number")
}

fn load<T: DeserializeOwned>(file: &str) -> (Value, Vec<T>) {
    let text = fs::read_to_string(package_dir().join("fixtures").join(file))
        .unwrap_or_else(|e| panic!("{file}: {e}"));
    let original: Value = serde_json::from_str(&text).unwrap_or_else(|e| panic!("{file}: {e}"));
    let typed = serde_json::from_value(original.clone()).unwrap_or_else(|e| panic!("{file}: {e}"));
    (original, typed)
}

/// Round-trips a fixture through `T` and returns `(type name, TS constant)`.
fn check_fixture<T: Serialize + DeserializeOwned + TS>(file: &str, const_name: &str, cfg: &Config) -> (String, String) {
    let (original, typed) = load::<T>(file);
    // Via a string so f32 values compare as written, not widened to f64.
    let back: Value = serde_json::from_str(&serde_json::to_string(&typed).unwrap()).unwrap();
    assert_eq!(original, back, "{file} does not round-trip through {}", T::name(cfg));
    let name = T::name(cfg);
    let body = serde_json::to_string_pretty(&original).unwrap();
    (name.clone(), format!("export const {const_name}: {name}[] = {body};\n"))
}

#[test]
fn contracts_round_trip_and_export() {
    let cfg = config();
    let out = cfg.out_dir().to_path_buf();
    fs::create_dir_all(&out).unwrap();
    // Start clean so a renamed or deleted type leaves no stale binding behind.
    for entry in fs::read_dir(&out).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|ext| ext == "ts") {
            fs::remove_file(path).unwrap();
        }
    }

    macro_rules! export {
        ($($t:ty),* $(,)?) => { $( <$t>::export_all(&cfg).expect(stringify!($t)); )* };
    }
    export!(
        ActivityEvent, BrowserHeartbeat, ExtensionStatus, Classification, Override, Session, Trigger, UserAction,
        LineRequest, LineResponse, ApiError, RegisterRequest, RegisterResponse, SpokenLine,
        ReminderDraft, Reminder, Settings,
    );

    let fixtures = [
        check_fixture::<ActivityEvent>("activity_event.json", "activityEvents", &cfg),
        check_fixture::<BrowserHeartbeat>("browser_heartbeat.json", "browserHeartbeats", &cfg),
        check_fixture::<ExtensionStatus>("extension_status.json", "extensionStatuses", &cfg),
        check_fixture::<Classification>("classification.json", "classifications", &cfg),
        check_fixture::<Override>("override.json", "overrides", &cfg),
        check_fixture::<Session>("session.json", "sessions", &cfg),
        check_fixture::<Trigger>("trigger.json", "triggers", &cfg),
        check_fixture::<UserAction>("user_action.json", "userActions", &cfg),
        check_fixture::<LineRequest>("line_request.json", "lineRequests", &cfg),
        check_fixture::<LineResponse>("line_response.json", "lineResponses", &cfg),
        check_fixture::<ApiError>("api_error.json", "apiErrors", &cfg),
        check_fixture::<RegisterRequest>("register_request.json", "registerRequests", &cfg),
        check_fixture::<RegisterResponse>("register_response.json", "registerResponses", &cfg),
        check_fixture::<SpokenLine>("spoken_line.json", "spokenLines", &cfg),
        check_fixture::<ReminderDraft>("reminder_draft.json", "reminderDrafts", &cfg),
        check_fixture::<Reminder>("reminder.json", "reminders", &cfg),
        check_fixture::<Settings>("settings.json", "settings", &cfg),
    ];

    let mut ts = String::from(HEADER);
    for (name, _) in &fixtures {
        ts.push_str(&format!("import type {{ {name} }} from \"./{name}\";\n"));
    }
    for (_, constant) in &fixtures {
        ts.push('\n');
        ts.push_str(constant);
    }
    fs::write(out.join("fixtures.ts"), ts).unwrap();

    fs::write(out.join("constants.ts"), constants::typescript()).unwrap();

    let mut types: Vec<String> = fs::read_dir(&out)
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|ext| ext == "ts"))
        .map(|p| p.file_stem().unwrap().to_string_lossy().into_owned())
        .filter(|stem| !matches!(stem.as_str(), "index" | "fixtures" | "constants"))
        .collect();
    types.sort();
    let mut index = String::from(HEADER);
    for name in &types {
        index.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
    }
    index.push_str("export * from \"./constants\";\n");
    fs::write(out.join("index.ts"), index).unwrap();
}

#[test]
fn settings_fixture_documents_the_defaults() {
    let (_, settings) = load::<Settings>("settings.json");
    assert_eq!(settings[0], Settings::default());
}

#[test]
fn foreground_keys_never_contain_titles() {
    let (_, events) = load::<ActivityEvent>("activity_event.json");
    let keys: Vec<String> = events.iter().map(|e| e.foreground.key()).collect();
    assert_eq!(keys, ["app:code.exe", "web:instagram.com", "app:winword.exe", "app:teams.exe", "private", "none"]);
    for event in &events {
        if let Some(title) = event.foreground.title() {
            assert!(!event.foreground.key().contains(title));
            assert!(!event.foreground.display_name().contains(title));
        }
    }
}

#[test]
fn calls_fullscreen_and_lock_silence_the_character() {
    let (_, events) = load::<ActivityEvent>("activity_event.json");
    let silenced: Vec<bool> = events.iter().map(ActivityEvent::silences_character).collect();
    // Teams call (mic in use) and the lock screen; idle in Word does not silence.
    assert_eq!(silenced, [false, false, false, true, false, true]);
}

#[test]
fn constants_match_the_spec() {
    assert_eq!(constants::DRIFT_THRESHOLD_MS, 5 * 60 * 1000);
    assert_eq!(constants::SWITCH_GRACE_MS, 30 * 1000);
    assert_eq!(constants::IDLE_FOCUSED_GRACE_MS, 10 * 60 * 1000);
    assert_eq!(constants::STREAK_MILESTONES_MIN, [25, 45, 90]);
    assert_eq!(constants::WAKE_QUIET_MS, 60 * 1000);
    assert_eq!(constants::LINE_MAX_CHARS, 140);
    assert_eq!(constants::RAW_EVENT_RETENTION_DAYS, 30);
    assert_eq!(Settings::default().drift_threshold_min, 5);
}
